    VERIFIED = "VERIFIED"
    VERIFIED_WITH_WARNING = "VERIFIED_WITH_WARNING"
    UNVERIFIED_KEY = "UNVERIFIED_KEY"
    TAMPERED_OUTPUT = "TAMPERED_OUTPUT"
